"""Turns the listening corpus files (tests/corpus/listen/*.tsv) into a C header for the research firmware's
`play` command (FR-LST-03):  gen-listen-header.py <corpus dir> <out.h>

One table per language: { id, text }. The text is the corpus' own, as C strings (UTF-8 bytes kept)."""

import sys
from pathlib import Path

SPDX = "SPDX-License" + "-Identifier: GPL-3.0-or-later"  # not a header of this file: the one it writes


def c_string(s: str) -> str:
    return (
        '"'
        + "".join(
            f"\\x{b:02x}" if b >= 0x80 or b < 0x20 or b in (0x22, 0x5C) else chr(b) for b in s.encode("utf-8")
        )
        + '"'
    )


def main(corpus: Path, out: Path) -> None:
    lines = [
        "/* " + SPDX + " */",
        "/* Generated by scripts/gen-listen-header.py: do not edit. */",
        "#pragma once",
        "typedef struct { const char *id, *text; } listen_item_t;",
    ]
    langs = []
    for tsv in sorted(corpus.glob("*.tsv")):
        lang = tsv.stem
        rows = [
            ln.split("\t")
            for ln in tsv.read_text(encoding="utf-8").splitlines()
            if ln and not ln.startswith("#")
        ]
        ident = lang.replace("-", "_")
        lines.append(f"static const listen_item_t listen_{ident}[] = {{")
        lines += [f"    {{{c_string(r[0])}, {c_string(r[2])}}}," for r in rows]
        lines.append("};")
        langs.append((lang, ident))
    lines.append(
        "typedef struct { const char *voice; const listen_item_t *items; unsigned n; } listen_set_t;"
    )
    lines.append("static const listen_set_t listen_sets[] = {")
    lines += [
        f'    {{"{lang}", listen_{ident}, sizeof listen_{ident} / sizeof listen_{ident}[0]}},'
        for lang, ident in langs
    ]
    lines.append("};")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
