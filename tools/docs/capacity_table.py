"""The capacity table of the README, from the real data (FR-CAP-11).

    capacity_table.py [--data <espeak-ng-data>] [--write README.md]

Prints the table of image size and PSRAM peak for the selections the README talks about, computed by
components/espeak-ng/tools/capacity.py over the compiled upstream data (the same numbers the build report
gives). With --write the block between the `capacity:start` and `capacity:end` markers of a README is
replaced. A number in the README is never typed by hand.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "components/espeak-ng/tools"))
sys.path.insert(0, str(ROOT / "tools/ref"))
import capacity  # noqa: E402
import gen_image  # noqa: E402

START = "<!-- capacity:start (generated by tools/docs/capacity_table.py: do not edit by hand) -->"
END = "<!-- capacity:end -->"


def figures(data: Path, languages: list[str] | None, all_languages: bool) -> tuple[int, int, str]:
    ns = argparse.Namespace(
        data=data,
        languages=" ".join(languages or []),
        all=all_languages,
        default_voice=(languages or ["en"])[0],
        partition_bytes=0,
        partitions=None,
        label="espeak",
        budget_kb=10**6,
        warn_pct=100,
        map=None,
        task_stack=0,
        task_stack_psram="y",
    )
    report, _image = capacity.analyse(ns)
    files = gen_image.select(data, report["languages"])
    biggest = max((n for n in files if n.endswith("_dict")), key=lambda n: files[n].stat().st_size)
    return report["image_bytes"], report["psram_peak_bytes"], biggest


def table(data: Path) -> str:
    rows = []
    for label, langs, every in (
        ("English only (`en`, the default)", ["en"], False),
        ("`pt-br` and `en` (the research firmware)", ["pt-br", "en"], False),
        ("every language with a compiled dictionary", None, True),
    ):
        image, peak, biggest = figures(data, langs, every)
        rows.append(f"| {label} | {image:,} B | {peak:,} B (largest dictionary: `{biggest}`) |")
    head = [
        "| Languages in the image | Data image | PSRAM peak (common files + largest dictionary) |",
        "|---|---|---|",
    ]
    return "\n".join([START, *head, *rows, END])


def rewrite(readme: Path, block: str) -> None:
    text = readme.read_text(encoding="utf-8")
    a, b = text.index(START), text.index(END) + len(END)
    readme.write_text(text[:a] + block + text[b:], encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--data", type=Path)
    ap.add_argument("--write", type=Path)
    a = ap.parse_args(argv)
    import r1

    data = a.data or r1.build(r1.upstream()) / "espeak-ng-data"
    block = table(data)
    if a.write:
        rewrite(a.write, block)
    else:
        print(block)
    return 0


if __name__ == "__main__":
    sys.exit(main())
